export function normalizeLanguage(value) {
  if (typeof value !== 'string') return 'vi';
  const v = value.trim().toLowerCase();
  return v === 'en' ? 'en' : 'vi';
}

export function loadLanguage(storage) {
  return 'vi';
}

export function saveLanguage(storage, value) {
  const lang = normalizeLanguage(value);
  try {
    if (storage && typeof storage.setItem === 'function') {
      storage.setItem('task-manager.language', lang);
    }
  } catch {}
  return lang;
}

const EN_KEYS = Object.keys(DICT).sort((a, b) => b.length - a.length);
const EN_PATTERN = new RegExp(EN_KEYS.map(k => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const translateChunk = s => s.replace(EN_PATTERN, m => Object.hasOwn(DICT, m) ? DICT[m] : m);

export function createTranslator(language) {
  const lang = normalizeLanguage(language);
  if (lang === 'vi') {
    return {
      html: (strings, ...values) => {
        let out = '';
        for (let i = 0; i < strings.length; i++) {
          out += strings[i];
          if (i < values.length) out += values[i];
        }
        return out;
      },
      text: s => s == null ? '' : String(s)
    };
  }
  return {
    html: (strings, ...values) => {
      let out = '';
      for (let i = 0; i < strings.length; i++) {
        out += translateChunk(strings[i]);
        if (i < values.length) out += values[i];
      }
      return out;
    },
    text: s => s == null ? '' : (Object.hasOwn(DICT, s) ? DICT[s] : String(s))
  };
}
